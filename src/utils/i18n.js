export const initialLanguage = () => {
  const linkedLanguage = new URLSearchParams(window.location.search).get('lang');

  if (SUPPORTED_LANGUAGES.includes(linkedLanguage)) {
    return linkedLanguage;
  }

  try {
    const storedLanguage = localStorage.getItem('cv-language');

    return SUPPORTED_LANGUAGES.includes(storedLanguage) ? storedLanguage : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
};

export const translate = (language, text) => {
  return language === Language.TURKISH ? (turkish[text] ?? text) : text;
};
